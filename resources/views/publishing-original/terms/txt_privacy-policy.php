1. Purpose of Collection and Use of Personal Information <br/>
The organizer collects and uses the personal information of applicants for the Global Korea Forum 2026 for the following purposes:<br/>
Registration and confirmation of participation<br/>
Identity verification<br/>
Event operation and participant management<br/>
Delivery of event-related notices and announcements<br/>
Distribution of event-related promotional content, including newsletters<br/>
Post-event satisfaction surveys and information on future events<br/>
<br/>
2. Personal Information Collected<br/>
The organizer collects the following personal information: full name, affiliation, job title, mobile phone number, email address, and session attendance.<br/>
<br/>
3. Retention and Use of Personal Information<br/>
The collected personal information will be retained and used for two (2) years from the date on which the purposes of collection and use have been fulfilled. Upon expiration <br class="pc_vw"/>
of the retention period, the personal information will be securely destroyed without delay in accordance with applicable laws and regulations. However, where retention is required <br class="pc_vw"/>
by applicable law, the information will be retained for the period prescribed by such laws.
